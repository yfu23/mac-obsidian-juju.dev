import AppKit
import ObsidianJujuCore
import SwiftUI

extension NSAttributedString.Key {
    /// Markdown syntax (`**`, `# `, `[[`, …) that live preview hides unless the caret is on its line.
    static let jujuHidden = NSAttributedString.Key("jujuHidden")
    /// A callout block shown as a box (`CalloutDecoration`); `JujuLayoutManager` draws it.
    static let jujuCallout = NSAttributedString.Key("jujuCallout")
}

/// Where an image embedded in a note comes from, for the editor's inline images.
enum EditorImageSource: Hashable {
    case file(URL)
    /// A JujuPix `.jjpx` photo, decrypted in memory when JujuPix photos are unlocked.
    case encrypted(URL)
    case remote(URL)
}

/// Obsidian-style live preview for the note editor: Markdown styles show as you type (bold, italic, headings,
/// highlights, …), their syntax characters are hidden except on the caret's line, and embedded images appear
/// under their line. It only changes how the text is displayed — attributes and overlay views — never the text
/// itself, so what is saved is exactly what was typed.
@MainActor
final class LivePreview: NSObject, NSLayoutManagerDelegate {
    weak var textView: NSTextView?
    /// Embed target as written (`photo.png`, `juju:a.png`, `https://…`) → where to load it from.
    var resolveImage: ((String) -> EditorImageSource?)?
    /// Decrypts a `.jjpx` file's bytes; nil while JujuPix photos are locked. Called off the main thread.
    var decrypt: (@Sendable (Data) -> Data?)?

    private var reveal = NSRange(location: NSNotFound, length: 0) {
        didSet { revealLock.withLock { revealShared = reveal } }
    }
    /// Copy of `reveal` for the layout manager delegate, which may be called off the main thread.
    nonisolated(unsafe) private var revealShared = NSRange(location: NSNotFound, length: 0)
    private let revealLock = NSLock()
    /// The editor font the current styling was built with (to restyle after font/zoom changes).
    private(set) var appliedFont: NSFont?
    private var detached = false
    /// Text length when the styling (and the stored ranges: frontmatter, images) was computed. A different length
    /// means the text just changed and a restyle is coming; until then the stored ranges are stale.
    private var styledLength = -1
    private var isStale: Bool { (textView?.string as NSString?)?.length != styledLength }
    private var images: [EditorImageSource: NSImage] = [:]
    private var pending: Set<EditorImageSource> = []
    private var unavailable: Set<EditorImageSource> = []
    private struct Placed {
        let paragraph: NSRange
        let image: NSImage?
        let size: NSSize
        let offset: CGFloat
        /// A video (iframe) thumbnail: drawn with a play button; `label` names a site without a thumbnail.
        var video = false
        var label: String?
    }
    private var placed: [Placed] = []
    private var imageViews: [OverlayView] = []
    /// Callout blocks (`> [!type]` and the lines after it), and the ones the caret is in. Those show as plain
    /// source; the others as boxes, as in Obsidian.
    private var callouts: [NSRange] = []
    private var openCallouts: [NSRange] = []
    /// The reveal range when the glyphs were last regenerated by a restyle.
    private var lastReveal: NSRange?
    /// Nothing is shown as source until the user moves the caret or types, so a note opens fully rendered
    /// (its first line is often an embed).
    private var holdReveal = true
    private var lastWidth: CGFloat = 0
    /// The frontmatter block, always shown as the Properties panel (the caret never goes into it).
    private var frontmatter: NSRange?
    /// "Add file property" (CC+;): the panel shows its new-property row, even if the note has no properties yet.
    private var addRequested = false
    private var emptyNoteRoom: CGFloat?
    private var clamping = false
    private var properties: [Property] = []
    private var propertiesHost: PanelHostingView?
    private var propertiesHeight: CGFloat = 0

    nonisolated static var isEnabled: Bool { UserDefaults.standard.object(forKey: SettingsKey.livePreview) as? Bool ?? true }

    init(textView: NSTextView) {
        self.textView = textView
        super.init()
        textView.layoutManager?.delegate = self
        textView.layoutManager?.allowsNonContiguousLayout = true
        // Layout stays on the main thread (the glyph delegate reads live-preview state).
        textView.layoutManager?.backgroundLayoutEnabled = false
        textView.postsFrameChangedNotifications = true
        NotificationCenter.default.addObserver(self, selector: #selector(frameChanged), name: NSView.frameDidChangeNotification,
                                               object: textView)
    }

    /// The note was locked or its editor is going away: stop editing it from the panel.
    func detach() {
        detached = true
        if let host = propertiesHost, let window = host.window,
           let responder = window.firstResponder as? NSView, responder.isDescendant(of: host)
            || (responder as? NSText)?.delegate.map({ ($0 as? NSView)?.isDescendant(of: host) ?? false }) == true {
            window.makeFirstResponder(nil)
        }
        propertiesHost?.removeFromSuperview()
        propertiesHost = nil
        textView?.layoutManager?.delegate = nil
    }

    /// Forgets loaded images (e.g. JujuPix photos were locked or unlocked) and redraws.
    func reloadImages() {
        images.removeAll()
        unavailable.removeAll()
        restyle()
    }

    @objc private func frameChanged() {
        guard let tv = textView, abs(tv.frame.width - lastWidth) > 1 else { return }
        lastWidth = tv.frame.width
        // Image sizes depend on the width.
        DispatchQueue.main.async { [weak self] in self?.restyle() }
    }

    // MARK: Styling

    func restyle() {
        guard !detached, let tv = textView, let storage = tv.textStorage, !tv.hasMarkedText() else { return }
        appliedFont = EditorStyle.font
        styledLength = storage.length
        let base = EditorStyle.attributes
        let full = NSRange(location: 0, length: storage.length)
        placed = []
        frontmatter = nil
        emptyNoteRoom = nil
        storage.beginEditing()
        storage.setAttributes(base, range: full)
        callouts = []
        openCallouts = []
        if Self.isEnabled {
            let spans = MarkdownStyle.spans(in: tv.string)
            frontmatter = spans.first { $0.kind == .frontmatter }?.range
            callouts = spans.compactMap { if case .callout = $0.kind { return $0.range } else { return nil } }
            openCallouts = openCallouts(around: revealRange())
            for span in spans { style(span, storage) }
            if frontmatter == nil, addRequested { collapseFrontmatter(nil, storage) }
        }
        storage.endEditing()
        // Attribute-only changes don't regenerate glyphs: redo those whose hidden state may have changed (the
        // frontmatter, callouts switching between box and source, the previously revealed text).
        if let lm = tv.layoutManager {
            let previous = lastReveal
            lastReveal = reveal
            for r in [frontmatter, previous].compactMap({ $0 }) + callouts
            where r.location != NSNotFound && NSMaxRange(r) <= storage.length {
                lm.invalidateGlyphs(forCharacterRange: r, changeInLength: 0, actualCharacterRange: nil)
                lm.invalidateLayout(forCharacterRange: r, actualCharacterRange: nil)
            }
        }
        tv.typingAttributes = base
        if let room = emptyNoteRoom {
            // An empty note: the first line typed sits below the panel.
            let style = EditorStyle.paragraph.mutableCopy() as! NSMutableParagraphStyle
            style.paragraphSpacingBefore = room
            tv.typingAttributes[.paragraphStyle] = style
        }
        updateReveal(force: true)
        layoutImages()
        layoutProperties()
    }

    /// Where the note body starts (after the frontmatter), so a note opens with the Properties panel showing.
    static func bodyStart(of text: String) -> Int {
        guard let fm = MarkdownStyle.spans(in: text).first(where: { $0.kind == .frontmatter }) else { return 0 }
        let ns = text as NSString
        let end = NSMaxRange(fm.range)
        return min(end + 1, ns.length)
    }

    private func style(_ span: MarkdownSpan, _ s: NSTextStorage) {
        let baseSize = EditorStyle.font.pointSize
        func traits(_ t: NSFontTraitMask, _ r: NSRange) {
            s.enumerateAttribute(.font, in: r) { value, sub, _ in
                guard let font = value as? NSFont else { return }
                s.addAttribute(.font, value: NSFontManager.shared.convert(font, toHaveTrait: t), range: sub)
            }
        }
        func hide(_ ranges: [NSRange]) {
            for r in ranges {
                s.addAttributes([.foregroundColor: NSColor(Theme.textFaint), .jujuHidden: true], range: r)
            }
        }
        let content = span.markers.count == 2 && span.kind != .link
            ? NSRange(location: NSMaxRange(span.markers[0]), length: max(0, span.markers[1].location - NSMaxRange(span.markers[0])))
            : span.range
        switch span.kind {
        case .heading(let level):
            let scale: [CGFloat] = [1.618, 1.462, 1.318, 1.188, 1.076, 1]
            s.addAttribute(.font, value: NSFont.systemFont(ofSize: baseSize * scale[min(level, 6) - 1], weight: .bold), range: span.range)
            hide(span.markers)
        case .bold:
            traits(.boldFontMask, span.range); hide(span.markers)
        case .italic:
            traits(.italicFontMask, span.range); hide(span.markers)
        case .boldItalic:
            traits([.boldFontMask, .italicFontMask], span.range); hide(span.markers)
        case .strikethrough:
            s.addAttribute(.strikethroughStyle, value: NSUnderlineStyle.single.rawValue, range: content); hide(span.markers)
        case .highlight:
            s.addAttribute(.backgroundColor, value: NSColor(red: 1, green: 0.82, blue: 0, alpha: 0.4), range: content)
            hide(span.markers)
        case .code:
            s.addAttributes([.font: NSFont.monospacedSystemFont(ofSize: baseSize * 0.9, weight: .regular),
                             .backgroundColor: NSColor(Theme.backgroundSecondary)], range: span.range)
            hide(span.markers)
        case .link:
            s.addAttribute(.foregroundColor, value: NSColor(Theme.accent), range: span.range)
            hide(span.markers)
        case .quote:
            s.addAttribute(.foregroundColor, value: NSColor(Theme.textFaint), range: span.markers.first ?? span.range)
        case .frontmatter:
            collapseFrontmatter(span.range, s)
        case .codeBlock:
            s.addAttributes([.font: NSFont.monospacedSystemFont(ofSize: baseSize * 0.9, weight: .regular),
                             .foregroundColor: NSColor(Theme.textMuted)], range: span.range)
        case .embed(let target, let width):
            embed(target: target, width: width, span: span, s)
        case .callout(let type, let title, let fold):
            callout(type: type, title: title, fold: fold, span: span, s)
        case .iframe(let src, let width, let height):
            iframe(src: src, width: width, height: height, span: span, s)
        }
    }

    // MARK: Callouts

    /// A callout the caret isn't in shows as Obsidian's box: tinted background, icon and title, `>` and `[!type]`
    /// hidden; a folded one (`[!type]-`) shows only its title. With the caret in it, it's plain source.
    private func callout(type: String, title: NSRange, fold: String, span: MarkdownSpan, _ s: NSTextStorage) {
        guard let tv = textView, !openCallouts.contains(span.range) else { return }
        let ns = tv.string as NSString
        let deco = CalloutDecoration(type: type, block: span.range, hasTitle: title.length > 0)
        s.addAttribute(.jujuCallout, value: deco, range: span.range)
        hideMarkers(span.markers, s)
        let font = EditorStyle.font
        let titleFont = NSFontManager.shared.convert(font, toHaveTrait: .boldFontMask)
        if title.length > 0 {
            s.addAttributes([.foregroundColor: deco.color, .font: titleFont], range: title)
        }
        let first = ns.paragraphRange(for: NSRange(location: span.range.location, length: 0))
        var paragraphs: [NSRange] = []
        ns.enumerateSubstrings(in: span.range, options: [.byParagraphs, .substringNotRequired]) { _, _, enclosing, _ in
            paragraphs.append(enclosing)
        }
        let folded = fold == "-"
        let lineHeight = ceil((font.ascender - font.descender + font.leading) * EditorStyle.paragraph.lineHeightMultiple)
        for (i, p) in paragraphs.enumerated() {
            if folded, i > 0 {
                // Collapsed: the content lines take no space (like the frontmatter).
                let tiny = NSMutableParagraphStyle()
                tiny.minimumLineHeight = 0.01
                tiny.maximumLineHeight = 0.01
                s.addAttributes([.jujuHidden: true, .paragraphStyle: tiny, .font: NSFont.systemFont(ofSize: 0.01)], range: p)
                continue
            }
            let current = s.attribute(.paragraphStyle, at: p.location, effectiveRange: nil) as? NSParagraphStyle
            let style = (current ?? EditorStyle.paragraph).mutableCopy() as! NSMutableParagraphStyle
            style.headIndent = CalloutDecoration.inset
            style.firstLineHeadIndent = p == first ? CalloutDecoration.titleInset : CalloutDecoration.inset
            style.tailIndent = -CalloutDecoration.padding
            if p == first { style.minimumLineHeight = lineHeight + CalloutDecoration.padding }   // room above the title
            if i == paragraphs.count - 1 || (folded && i == 0) { style.paragraphSpacing += CalloutDecoration.padding }
            s.addAttribute(.paragraphStyle, value: style, range: p)
        }
    }

    private func hideMarkers(_ ranges: [NSRange], _ s: NSTextStorage) {
        for r in ranges where NSMaxRange(r) <= s.length {
            s.addAttributes([.foregroundColor: NSColor(Theme.textFaint), .jujuHidden: true], range: r)
        }
    }

    /// The text shown as source: the caret's paragraph, widened to the whole callout around it.
    private func revealRange() -> NSRange {
        guard let tv = textView, !holdReveal else { return NSRange(location: NSNotFound, length: 0) }
        let ns = tv.string as NSString
        let sel = tv.selectedRange()
        guard NSMaxRange(sel) <= ns.length else { return NSRange(location: NSNotFound, length: 0) }
        var r = ns.paragraphRange(for: sel)
        for c in openCallouts(around: r) { r = NSUnionRange(r, ns.paragraphRange(for: c)) }
        return r
    }

    private func openCallouts(around r: NSRange) -> [NSRange] {
        guard r.location != NSNotFound else { return [] }
        return callouts.filter { c in r.location <= NSMaxRange(c) && NSMaxRange(r) > c.location }
    }

    // MARK: Iframes

    /// An `<iframe>` (YouTube etc.) shows as a thumbnail with a play button under its line, like Obsidian's live
    /// preview; its HTML is hidden except on the caret's line. The video plays in the reading view.
    private func iframe(src: String, width: Int?, height: Int?, span: MarkdownSpan, _ s: NSTextStorage) {
        guard let tv = textView, let tc = tv.textContainer else { return }
        let maxWidth = max(40, tc.size.width - 2 * tc.lineFragmentPadding)
        let w = min(CGFloat(width ?? 560), maxWidth)
        let aspect = CGFloat(height ?? 315) / CGFloat(max(1, width ?? 560))
        let size = NSSize(width: w, height: (w * aspect).rounded())
        var image: NSImage?
        var label: String?
        if let thumb = Self.videoThumbnail(src) {
            image = images[.remote(thumb)]
            if image == nil { load(.remote(thumb)) }
        } else {
            label = URL(string: src)?.host ?? src
        }
        place(Placed(paragraph: (tv.string as NSString).paragraphRange(for: span.range), image: image, size: size,
                     offset: 0, video: true, label: label), span: span, s)
    }

    /// YouTube's thumbnail for an embed/watch/short link (hqdefault: always there, 4:3 with bars cropped by the view).
    static func videoThumbnail(_ src: String) -> URL? {
        guard let url = URL(string: src.hasPrefix("//") ? "https:" + src : src), let host = url.host?.lowercased() else { return nil }
        var id: String?
        if host.hasSuffix("youtu.be") {
            id = url.pathComponents.dropFirst().first
        } else if host.contains("youtube.com") || host.contains("youtube-nocookie.com") {
            let parts = url.pathComponents
            if let i = parts.firstIndex(where: { ["embed", "shorts", "live", "v"].contains($0) }), i + 1 < parts.count {
                id = parts[i + 1]
            } else {
                id = URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems?.first { $0.name == "v" }?.value
            }
        }
        guard let id, !id.isEmpty, id.allSatisfy({ $0.isLetter || $0.isNumber || $0 == "-" || $0 == "_" }) else { return nil }
        return URL(string: "https://i.ytimg.com/vi/\(id)/hqdefault.jpg")
    }

    /// Images show under their line (the line's paragraph spacing makes room); their source text is hidden except
    /// on the caret's line. Other embeds (notes, PDFs) are shown like links.
    private func embed(target: String, width: Int?, span: MarkdownSpan, _ s: NSTextStorage) {
        guard let source = resolveImage?(target) else {
            s.addAttribute(.foregroundColor, value: NSColor(Theme.accent), range: span.range)
            return
        }
        guard let image = images[source] else {
            s.addAttribute(.foregroundColor, value: NSColor(Theme.textFaint), range: span.range)
            load(source)
            return
        }
        guard let tv = textView, let tc = tv.textContainer, image.size.width > 0 else { return }
        let maxWidth = max(40, tc.size.width - 2 * tc.lineFragmentPadding)
        let w = min(CGFloat(width ?? Int(image.size.width)), maxWidth)
        let size = NSSize(width: w, height: (image.size.height * w / image.size.width).rounded())
        place(Placed(paragraph: (tv.string as NSString).paragraphRange(for: span.range), image: image, size: size, offset: 0),
              span: span, s)
    }

    /// Makes room under the embed's line for its overlay view and hides its source.
    private func place(_ item: Placed, span: MarkdownSpan, _ s: NSTextStorage) {
        let paragraph = item.paragraph
        // Several images on one line stack.
        let offset = placed.filter { $0.paragraph == paragraph }.reduce(0) { $0 + $1.size.height + 6 }
        placed.append(Placed(paragraph: paragraph, image: item.image, size: item.size, offset: offset, video: item.video, label: item.label))
        // Keep other paragraph settings (e.g. the room above the first line for the Properties panel).
        let current = s.attribute(.paragraphStyle, at: paragraph.location, effectiveRange: nil) as? NSParagraphStyle
        let style = ((current ?? EditorStyle.paragraph).mutableCopy() as! NSMutableParagraphStyle)
        style.paragraphSpacing = offset + item.size.height + 10
        s.addAttribute(.paragraphStyle, value: style, range: paragraph)
        s.addAttributes([.foregroundColor: NSColor(Theme.textFaint), .jujuHidden: true], range: span.range)
    }

    private func load(_ source: EditorImageSource) {
        guard !pending.contains(source), !unavailable.contains(source) else { return }
        pending.insert(source)
        let decrypt = decrypt
        let finish: @Sendable (Data?) -> Void = { data in
            DispatchQueue.main.async { [weak self] in
                guard let self else { return }
                self.pending.remove(source)
                if let data, let image = NSImage(data: data) { self.images[source] = image } else { self.unavailable.insert(source) }
                self.restyle()
            }
        }
        switch source {
        case .file(let url):
            DispatchQueue.global(qos: .userInitiated).async { finish(try? Data(contentsOf: url)) }
        case .encrypted(let url):
            DispatchQueue.global(qos: .userInitiated).async { finish((try? Data(contentsOf: url)).flatMap { decrypt?($0) }) }
        case .remote(let url):
            URLSession.shared.dataTask(with: url) { data, _, _ in finish(data) }.resume()
        }
    }

    private func layoutImages() {
        guard let tv = textView, let lm = tv.layoutManager, !isStale else { return }
        while imageViews.count < placed.count {
            let v = OverlayView()
            tv.addSubview(v)
            imageViews.append(v)
        }
        while imageViews.count > placed.count { imageViews.removeLast().removeFromSuperview() }
        let origin = tv.textContainerOrigin
        let padding = tv.textContainer?.lineFragmentPadding ?? 0
        let length = (tv.string as NSString).length
        for (view, item) in zip(imageViews, placed) where NSMaxRange(item.paragraph) <= length && length > 0 {
            var last = NSMaxRange(item.paragraph) - 1
            if last > item.paragraph.location, (tv.string as NSString).character(at: last) == 10 { last -= 1 }
            last = max(0, min(last, length - 1))
            lm.ensureLayout(forCharacterRange: NSRange(location: 0, length: last + 1))
            let glyph = lm.glyphIndexForCharacter(at: last)
            let used = lm.lineFragmentUsedRect(forGlyphAt: glyph, effectiveRange: nil)
            view.show(item.image, video: item.video, label: item.label)
            // Inside a callout box the embed is indented like its text.
            let indent = (tv.textStorage?.attribute(.paragraphStyle, at: item.paragraph.location, effectiveRange: nil) as? NSParagraphStyle)?.headIndent ?? 0
            view.frame = NSRect(x: origin.x + padding + indent, y: origin.y + used.maxY + 6 + item.offset,
                                width: item.size.width, height: item.size.height)
        }
    }

    // MARK: Properties panel

    func beginAddingProperty() {
        addRequested = true
        restyle()
    }

    /// The YAML takes no space (hidden glyphs, near-zero line height); the panel sits in the room made above the
    /// first body paragraph. `range` is nil for a note without frontmatter while a property is being added.
    private func collapseFrontmatter(_ range: NSRange?, _ s: NSTextStorage) {
        guard let tv = textView else { return }
        properties = Frontmatter.split(tv.string).properties
        let width = panelWidth
        let host = propertiesHost ?? {
            let h = PanelHostingView(rootView: panel(width: width))
            h.clipsToBounds = true   // never draws over the note, even before the next restyle
            h.sizeChanged = { [weak self] in self?.panelSizeChanged() }
            propertiesHost = h
            return h
        }()
        host.rootView = panel(width: width)
        propertiesHeight = ceil(host.fittingSize.height)
        let ns = tv.string as NSString
        let room = propertiesHeight + 16
        guard let range else {
            // No frontmatter yet (adding the first property): the first line grows by the panel's height, text at
            // its bottom. (TextKit ignores space before the first paragraph.)
            if ns.length == 0 { emptyNoteRoom = room; return }
            let first = ns.paragraphRange(for: NSRange(location: 0, length: 0))
            let font = EditorStyle.font
            let style = EditorStyle.paragraph.mutableCopy() as! NSMutableParagraphStyle
            style.minimumLineHeight = room + ceil((font.ascender - font.descender + font.leading) * style.lineHeightMultiple)
            s.addAttribute(.paragraphStyle, value: style, range: first)
            return
        }
        // The YAML takes no space (hidden glyphs, near-zero line height) except its closing line, which is exactly
        // as tall as the panel drawn over it, so the body starts right below the panel.
        let tiny = NSMutableParagraphStyle()
        tiny.minimumLineHeight = 0.01
        tiny.maximumLineHeight = 0.01
        s.addAttributes([.jujuHidden: true, .paragraphStyle: tiny, .font: NSFont.systemFont(ofSize: 0.01)], range: range)
        let closing = ns.paragraphRange(for: NSRange(location: max(range.location, NSMaxRange(range) - 1), length: 0))
        let tall = NSMutableParagraphStyle()
        tall.minimumLineHeight = room
        tall.maximumLineHeight = room
        s.addAttribute(.paragraphStyle, value: tall, range: closing)
    }

    private var panelWidth: CGFloat {
        guard let tc = textView?.textContainer else { return 400 }
        return max(200, tc.size.width - 2 * tc.lineFragmentPadding)
    }

    private func panel(width: CGFloat) -> PropertiesPanel {
        PropertiesPanel(
            properties: properties, width: width, fontSize: EditorStyle.font.pointSize, addRequested: addRequested,
            // Applied after SwiftUI finishes its update (edits often come from focus changes mid-update).
            edit: { [weak self] edit in DispatchQueue.main.async { self?.applyProperty(edit) } },
            relayout: { [weak self] in DispatchQueue.main.async { self?.restyle() } },
            addFinished: { [weak self] in self?.addRequested = false })
    }

    /// The panel's content grew or shrank by itself (a row wrapped, a field appeared): make room again.
    private func panelSizeChanged() {
        guard let host = propertiesHost, !detached, abs(ceil(host.fittingSize.height) - propertiesHeight) > 0.5 else { return }
        restyle()
    }

    private func layoutProperties() {
        guard let tv = textView, let host = propertiesHost else { return }
        guard Self.isEnabled, frontmatter != nil || addRequested else {
            host.removeFromSuperview()
            return
        }
        if host.superview !== tv { tv.addSubview(host) }
        let origin = tv.textContainerOrigin
        let padding = tv.textContainer?.lineFragmentPadding ?? 0
        host.frame = NSRect(x: origin.x + padding, y: origin.y, width: panelWidth, height: propertiesHeight)
    }

    /// Writes a panel edit into the note's YAML, replacing only the changed characters (undoable, autosaved).
    private func applyProperty(_ edit: Frontmatter.Edit) {
        guard !detached, let tv = textView, let new = Frontmatter.apply(edit, to: tv.string) else { return }
        let old = tv.string as NSString, next = new as NSString
        var p = 0
        let maxP = min(old.length, next.length)
        while p < maxP, old.character(at: p) == next.character(at: p) { p += 1 }
        var q = 0
        while q < maxP - p, old.character(at: old.length - 1 - q) == next.character(at: next.length - 1 - q) { q += 1 }
        let range = NSRange(location: p, length: old.length - p - q)
        let replacement = next.substring(with: NSRange(location: p, length: next.length - p - q))
        if let vtv = tv as? VimTextView, vtv.vimActive {
            vtv.syncFromView()
            vtv.vim.recordUndoPoint()
        }
        let sel = tv.selectedRange()
        tv.breakUndoCoalescing()   // its own undo step, not merged with typing
        guard tv.shouldChangeText(in: range, replacementString: replacement) else { return }
        tv.textStorage?.replaceCharacters(in: range, with: replacement)
        tv.didChangeText()
        // Keep the caret where it was in the body.
        let delta = next.length - old.length
        if sel.location >= NSMaxRange(range) {
            tv.setSelectedRange(NSRange(location: min(sel.location + delta, next.length), length: sel.length))
        }
        (tv as? VimTextView)?.syncFromView()
    }

    // MARK: Showing syntax on the caret's line

    func selectionChanged() {
        // Mid-edit (AppKit adjusts the selection while the text is still changing): wait for the restyle.
        guard !detached, !isStale else { return }
        if !clamping { holdReveal = false }
        // The caret stays out of the hidden YAML (properties are edited in the panel), as in Obsidian.
        if let tv = textView, let fm = frontmatter, Self.isEnabled, !clamping {
            let sel = tv.selectedRange()
            if sel.length == 0, sel.location <= NSMaxRange(fm) {
                let body = min(NSMaxRange(fm) + 1, (tv.string as NSString).length)
                if sel.location != body {
                    clamping = true
                    tv.setSelectedRange(NSRange(location: body, length: 0))
                    (tv as? VimTextView)?.syncFromView()
                    clamping = false
                }
            }
        }
        updateReveal(force: false)
    }

    private func updateReveal(force: Bool) {
        guard let tv = textView, let lm = tv.layoutManager else { return }
        let ns = tv.string as NSString
        let now = revealRange()
        guard force || now != reveal else { return }
        // The caret moved into or out of a callout: it switches between box and source (paragraph styles change).
        if !force, openCallouts(around: now) != openCallouts {
            restyle()
            return
        }
        let old = reveal
        reveal = now
        guard !force else { return }   // a restyle already regenerates every glyph
        for r in [old, now] where r.location != NSNotFound && NSMaxRange(r) <= ns.length {
            lm.invalidateGlyphs(forCharacterRange: r, changeInLength: 0, actualCharacterRange: nil)
            lm.invalidateLayout(forCharacterRange: r, actualCharacterRange: nil)
        }
        layoutImages()
    }

    nonisolated func layoutManager(_ layoutManager: NSLayoutManager, shouldGenerateGlyphs glyphs: UnsafePointer<CGGlyph>,
                       properties props: UnsafePointer<NSLayoutManager.GlyphProperty>,
                       characterIndexes charIndexes: UnsafePointer<Int>, font aFont: NSFont,
                       forGlyphRange glyphRange: NSRange) -> Int {
        guard let storage = layoutManager.textStorage, Self.isEnabled else { return 0 }
        var changed: [NSLayoutManager.GlyphProperty]?
        let reveal = revealLock.withLock { revealShared }
        for i in 0..<glyphRange.length {
            let c = charIndexes[i]
            guard c < storage.length, storage.attribute(.jujuHidden, at: c, effectiveRange: nil) != nil,
                  !(reveal.location != NSNotFound && c >= reveal.location && c < NSMaxRange(reveal)) else { continue }
            // Line breaks stay: hiding them would merge the lines (the frontmatter's would swallow the next line).
            guard !props[i].contains(.controlCharacter) else { continue }
            if changed == nil { changed = Array(UnsafeBufferPointer(start: props, count: glyphRange.length)) }
            changed![i] = .null
        }
        guard let changed else { return 0 }
        layoutManager.setGlyphs(glyphs, properties: changed, characterIndexes: charIndexes, font: aFont, forGlyphRange: glyphRange)
        return glyphRange.length
    }
}

/// The Properties panel's host; reports when SwiftUI changes the panel's size on its own.
final class PanelHostingView: NSHostingView<PropertiesPanel> {
    var sizeChanged: (() -> Void)?
    private var lastHeight: CGFloat = 0

    override func layout() {
        super.layout()
        let h = ceil(fittingSize.height)
        guard abs(h - lastHeight) > 0.5 else { return }
        lastHeight = h
        DispatchQueue.main.async { [weak self] in self?.sizeChanged?() }
    }
}

/// An inline image or video thumbnail under its line. It doesn't take clicks: clicking it puts the caret in the
/// text, as in Obsidian.
private final class OverlayView: NSView {
    private var image: NSImage?
    private var video = false
    private var label: String?

    override var isFlipped: Bool { true }
    override func hitTest(_ point: NSPoint) -> NSView? { nil }

    func show(_ image: NSImage?, video: Bool, label: String?) {
        guard image !== self.image || video != self.video || label != self.label else { return }
        self.image = image
        self.video = video
        self.label = label
        needsDisplay = true
    }

    override func draw(_ dirtyRect: NSRect) {
        NSBezierPath(roundedRect: bounds, xRadius: 4, yRadius: 4).addClip()
        if let image, image.size.width > 0, image.size.height > 0 {
            // Fill the frame, cropping overflow (YouTube's 4:3 thumbnails have bars above and below).
            let scale = max(bounds.width / image.size.width, bounds.height / image.size.height)
            let w = bounds.width / scale, h = bounds.height / scale
            let from = NSRect(x: (image.size.width - w) / 2, y: (image.size.height - h) / 2, width: w, height: h)
            image.draw(in: bounds, from: from, operation: .sourceOver, fraction: 1, respectFlipped: true, hints: nil)
        } else if video {
            NSColor(white: 0.12, alpha: 1).setFill()
            bounds.fill()
        }
        guard video else { return }
        let b = NSRect(x: bounds.midX - 34, y: bounds.midY - 24, width: 68, height: 48)
        NSColor(red: 1, green: 0, blue: 0, alpha: 0.9).setFill()
        NSBezierPath(roundedRect: b, xRadius: 12, yRadius: 12).fill()
        let t = NSBezierPath()
        t.move(to: NSPoint(x: b.midX - 9, y: b.midY - 11))
        t.line(to: NSPoint(x: b.midX - 9, y: b.midY + 11))
        t.line(to: NSPoint(x: b.midX + 13, y: b.midY))
        t.close()
        NSColor.white.setFill()
        t.fill()
        if let label {
            let p = NSMutableParagraphStyle()
            p.alignment = .center
            (label as NSString).draw(in: NSRect(x: 8, y: bounds.maxY - 28, width: bounds.width - 16, height: 18), withAttributes: [
                .font: NSFont.systemFont(ofSize: 12), .foregroundColor: NSColor.white.withAlphaComponent(0.8), .paragraphStyle: p,
            ])
        }
    }
}

/// How a callout box looks (Obsidian's default theme colors and Lucide-like icons as SF Symbols).
final class CalloutDecoration: NSObject {
    static let padding: CGFloat = 12
    static let inset: CGFloat = 24
    static let iconSize: CGFloat = 18
    static var titleInset: CGFloat { inset + iconSize + 6 }

    let type: String
    let block: NSRange
    let hasTitle: Bool
    let color: NSColor
    let symbol: String

    init(type: String, block: NSRange, hasTitle: Bool) {
        self.type = type
        self.block = block
        self.hasTitle = hasTitle
        let (rgb, symbol): ((Int, Int, Int), String) = switch type {
        case "abstract", "summary", "tldr": ((0, 191, 188), "list.clipboard")
        case "info": ((8, 109, 221), "info.circle")
        case "todo": ((8, 109, 221), "checkmark.circle")
        case "tip", "hint", "important": ((0, 191, 188), "flame")
        case "success", "check", "done": ((8, 185, 78), "checkmark")
        case "question", "help", "faq": ((236, 117, 0), "questionmark.circle")
        case "warning", "caution", "attention": ((236, 117, 0), "exclamationmark.triangle")
        case "failure", "fail", "missing": ((233, 49, 71), "xmark")
        case "danger", "error": ((233, 49, 71), "bolt")
        case "bug": ((233, 49, 71), "ladybug")
        case "example": ((120, 82, 238), "list.bullet")
        case "quote", "cite": ((158, 158, 158), "quote.opening")
        default: ((8, 109, 221), "pencil")
        }
        color = NSColor(red: CGFloat(rgb.0) / 255, green: CGFloat(rgb.1) / 255, blue: CGFloat(rgb.2) / 255, alpha: 1)
        self.symbol = symbol
    }

    /// Shown when the callout has no title: the type, capitalized ("Info").
    var defaultTitle: String { type.prefix(1).uppercased() + type.dropFirst() }
}

/// Draws callout boxes behind their text (live preview).
final class JujuLayoutManager: NSLayoutManager {
    override func drawBackground(forGlyphRange glyphsToShow: NSRange, at origin: NSPoint) {
        super.drawBackground(forGlyphRange: glyphsToShow, at: origin)
        guard let storage = textStorage, let container = textContainers.first, storage.length > 0 else { return }
        let chars = characterRange(forGlyphRange: glyphsToShow, actualGlyphRange: nil)
        var drawn = Set<ObjectIdentifier>()
        storage.enumerateAttribute(.jujuCallout, in: chars) { value, _, _ in
            guard let deco = value as? CalloutDecoration, drawn.insert(ObjectIdentifier(deco)).inserted,
                  deco.block.length > 0, NSMaxRange(deco.block) <= storage.length else { return }
            draw(deco, container: container, origin: origin, font: storage.attribute(.font, at: deco.block.location, effectiveRange: nil) as? NSFont)
        }
    }

    private func draw(_ deco: CalloutDecoration, container: NSTextContainer, origin: NSPoint, font: NSFont?) {
        // With its line break: a last line of only hidden glyphs (`>`) belongs to the fragment of that break.
        let chars = (textStorage?.string as NSString?)?.paragraphRange(for: deco.block) ?? deco.block
        let glyphs = glyphRange(forCharacterRange: chars, actualCharacterRange: nil)
        var box = NSRect.null
        var titleLine: (rect: NSRect, glyph: Int)?
        enumerateLineFragments(forGlyphRange: glyphs) { rect, used, _, range, _ in
            guard rect.height > 0.5 else { return }   // a folded callout's hidden lines
            if titleLine == nil { titleLine = (rect, range.location) }
            box = box.union(rect)
        }
        guard !box.isNull, let titleLine else { return }
        let padding = container.lineFragmentPadding
        box.origin.x = padding
        box.size.width = container.size.width - 2 * padding
        box = box.offsetBy(dx: origin.x, dy: origin.y)
        deco.color.withAlphaComponent(0.1).setFill()
        NSBezierPath(roundedRect: box, xRadius: 4, yRadius: 4).fill()

        // Icon (and the default title) on the title line, vertically centered on its text.
        let font = font ?? NSFont.systemFont(ofSize: NSFont.systemFontSize)
        let titleFont = NSFontManager.shared.convert(font, toHaveTrait: .boldFontMask)
        let textHeight = ceil(titleFont.ascender - titleFont.descender)
        let baseline = origin.y + titleLine.rect.minY + location(forGlyphAt: titleLine.glyph).y
        let midY = baseline - titleFont.capHeight / 2
        let size = CalloutDecoration.iconSize
        let config = NSImage.SymbolConfiguration(pointSize: size * 0.8, weight: .semibold)
            .applying(.init(paletteColors: [deco.color]))
        if let icon = NSImage(systemSymbolName: deco.symbol, accessibilityDescription: nil)?.withSymbolConfiguration(config) {
            let s = icon.size
            let scale = min(size / max(s.width, 1), size / max(s.height, 1), 1)
            let r = NSRect(x: origin.x + padding + CalloutDecoration.inset, y: midY - s.height * scale / 2,
                           width: s.width * scale, height: s.height * scale)
            icon.draw(in: r, from: .zero, operation: .sourceOver, fraction: 1, respectFlipped: true, hints: nil)
        }
        if !deco.hasTitle {
            let attrs: [NSAttributedString.Key: Any] = [.font: titleFont, .foregroundColor: deco.color]
            (deco.defaultTitle as NSString).draw(at: NSPoint(x: origin.x + padding + CalloutDecoration.titleInset,
                                                             y: baseline - titleFont.ascender), withAttributes: attrs)
        }
    }
}
